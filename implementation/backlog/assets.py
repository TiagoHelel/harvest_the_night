# -*- coding: utf-8 -*-
"""The art request queue: what Codex generates for HARVEST THE NIGHT 1.0.

Every pack is one file in implementation/backlog/packs/ (A001-slug.md) with a
Status line, the same way a game task is a prompt with a Status line. Codex
works the packs; Claude's game tasks integrate them once they are approved.

    python implementation/backlog/assets.py next              the pack to work on now
    python implementation/backlog/assets.py list [status]     every pack, or one status
    python implementation/backlog/assets.py status A012       one pack's status
    python implementation/backlog/assets.py set A012 review   change a status (+ optional note)
    python implementation/backlog/assets.py stats
    python implementation/backlog/assets.py index             rebuild INDEX.md
    python implementation/backlog/assets.py unblock           reopen game tasks whose art arrived
    python implementation/backlog/assets.py check             validate packs and the index

Statuses, in order: todo -> generating -> review -> approved -> integrated,
or blocked (with a note). Codex moves a pack up to `approved` only with the
owner's words in its APPROVAL.json; `integrated` is set by the Claude task
that put the art into the game.

`unblock` is the hand-off back to the game loop: a game task that found its
pack missing marked itself `blocked - waiting for asset Axxx (Codex)`; once
every pack named in that note is approved, it goes back to `todo` and the
loop picks it up on its next turn.
"""
import glob
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
PACKS = os.path.join(HERE, "packs")
INDEX = os.path.join(HERE, "INDEX.md")
GAME_PROMPTS = os.path.join(ROOT, "implementation", "prompts")

STATUSES = ("todo", "generating", "review", "approved", "integrated", "blocked")
READY = ("approved", "integrated")

RE_STATUS = re.compile(r"^- \*\*Status:\*\* (\w+)(.*)$", re.M)
RE_FOR = re.compile(r"^- \*\*For game tasks?:\*\* (.+)$", re.M)
RE_SPEC = re.compile(r"^- \*\*Spec after game task:\*\* (\d{4})", re.M)
RE_PACK = re.compile(r"\bA\d{3}\b")
RE_ID = re.compile(r"^(A\d{3})-[a-z0-9-]+\.md$")


def load():
    packs = []
    for path in sorted(glob.glob(os.path.join(PACKS, "A*.md"))):
        base = os.path.basename(path)
        m = RE_ID.match(base)
        if not m:
            continue
        text = open(path, encoding="utf-8").read()
        st = RE_STATUS.search(text)
        fr = RE_FOR.search(text)
        sp = RE_SPEC.search(text)
        head = text.split("\n", 1)[0].lstrip("# ").strip()
        head = re.sub(r"^A\d{3}\s*-\s*", "", head)
        packs.append({
            "id": m.group(1),
            "path": path,
            "title": head,
            "status": st.group(1) if st else "?",
            "note": (st.group(2) or "").strip(" -") if st else "",
            "for": [int(x) for x in re.findall(r"\d{4}", fr.group(1))] if fr else [],
            "spec_after": int(sp.group(1)) if sp else 0,
        })
    return packs


def spec_waiting(p, tasks=None):
    """The game task whose rules fix this pack's geometry, while it is not
    done yet - Codex leaves the pack alone until then. 0 when it can start."""
    if not p["spec_after"]:
        return 0
    tasks = tasks if tasks is not None else {t["id"]: t for t in game_tasks()}
    t = tasks.get(p["spec_after"])
    return 0 if t is not None and t["status"] == "done" else p["spec_after"]


def by_id(packs):
    return {p["id"]: p for p in packs}


def write_index(packs):
    counts = {s: 0 for s in STATUSES}
    for p in packs:
        counts[p["status"]] = counts.get(p["status"], 0) + 1
    lines = [
        "# Art packs for Codex - index",
        "",
        "Generated by `python implementation/backlog/assets.py index`. Do not edit by",
        "hand: change a pack's Status line with `assets.py set` and this file follows.",
        "",
        "**%d packs:** %s" % (len(packs), ", ".join(
            "%d %s" % (counts[s], s) for s in STATUSES if counts.get(s))),
        "",
        "Codex starts a pack only once the game task in *Starts after* is done:",
        "that task settles the pack's final geometry. A dash means it can start",
        "now.",
        "",
        "| Pack | Title | Status | Starts after | For game task | File |",
        "|---|---|---|---|---|---|",
    ]
    tasks = {t["id"]: t for t in game_tasks()}
    for p in packs:
        status = p["status"] + (" - " + p["note"] if p["note"] else "")
        after = spec_waiting(p, tasks)
        lines.append("| %s | %s | %s | %s | %s | [%s](packs/%s) |" % (
            p["id"], p["title"], status,
            ("%04d" % after) if after else "-",
            ", ".join("%04d" % t for t in p["for"]) or "-",
            os.path.basename(p["path"]), os.path.basename(p["path"])))
    lines.append("")
    open(INDEX, "w", encoding="utf-8", newline="\n").write("\n".join(lines))


def set_status(pid, status, note=""):
    if status not in STATUSES:
        sys.exit("status must be one of: " + ", ".join(STATUSES))
    if status == "blocked" and not note:
        sys.exit("a blocked pack needs a note saying why")
    packs = by_id(load())
    if pid not in packs:
        sys.exit("no pack %s" % pid)
    p = packs[pid]
    text = open(p["path"], encoding="utf-8").read()
    line = "- **Status:** " + status + ((" - " + note) if note else "")
    text, n = RE_STATUS.subn(line.replace("\\", "\\\\"), text, count=1)
    if n == 0:
        sys.exit("%s has no Status line" % p["path"])
    open(p["path"], "w", encoding="utf-8", newline="\n").write(text)
    print("%s %s -> %s%s" % (pid, p["title"], status, (" (%s)" % note) if note else ""))
    write_index(load())


def next_pack():
    packs = load()
    for p in packs:
        if p["status"] in ("generating", "review"):
            return p, "resume (was left %s)" % p["status"]
    tasks = {t["id"]: t for t in game_tasks()}
    waiting = []
    for p in packs:
        if p["status"] != "todo":
            continue
        if spec_waiting(p, tasks):
            waiting.append(p)
            continue
        return p, "next in order"
    if waiting:
        return None, ("nothing ready: %d pack(s) wait for the game task that "
                      "fixes their spec (%s)" % (len(waiting), ", ".join(
                          "%s after %04d" % (p["id"], p["spec_after"])
                          for p in waiting[:6])))
    return None, "nothing left to generate"


def game_tasks():
    out = []
    for path in sorted(glob.glob(os.path.join(GAME_PROMPTS, "*.md"))):
        base = os.path.basename(path)
        if not base[:4].isdigit():
            continue
        text = open(path, encoding="utf-8").read()
        m = RE_STATUS.search(text)
        out.append({"id": int(base[:4]), "path": path,
                    "status": m.group(1) if m else "todo",
                    "note": (m.group(2) or "").strip(" -") if m else ""})
    return out


def unblock():
    packs = by_id(load())
    reopened = 0
    for t in game_tasks():
        if t["status"] != "blocked" or "waiting for asset" not in t["note"]:
            continue
        wanted = RE_PACK.findall(t["note"])
        if not wanted:
            continue
        if all(w in packs and packs[w]["status"] in READY for w in wanted):
            subprocess.run([sys.executable, os.path.join(ROOT, "tools", "task.py"),
                            "todo", "%04d" % t["id"]], cwd=ROOT, check=True)
            reopened += 1
    print("reopened %d game task(s) whose art has arrived" % reopened)


def check():
    problems = []
    packs = load()
    seen = set()
    for p in packs:
        if p["id"] in seen:
            problems.append("duplicate pack id %s" % p["id"])
        seen.add(p["id"])
        if p["status"] not in STATUSES:
            problems.append("%s: bad or missing Status line" % p["id"])
        if p["status"] == "blocked" and not p["note"]:
            problems.append("%s: blocked without a note" % p["id"])
        if not p["for"]:
            problems.append("%s: no 'For game task' line" % p["id"])
    tasks = {t["id"]: t for t in game_tasks()}
    for p in packs:
        for t in p["for"]:
            if t not in tasks:
                problems.append("%s names game task %04d, which has no prompt" % (p["id"], t))
            elif p["id"] not in open(tasks[t]["path"], encoding="utf-8").read():
                problems.append("%s names game task %04d, which does not mention it"
                                % (p["id"], t))
    # Rebuilt every time, like gen_backlog's BACKLOG.md: a stale index is a
    # file to rewrite, not a failure.
    write_index(packs)
    for line in problems:
        print("  " + line)
    print("%d packs, %d problem(s)" % (len(packs), len(problems)))
    return 1 if problems else 0


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    cmd = sys.argv[1]
    if cmd == "next":
        p, why = next_pack()
        if p is None:
            print(why)
            return 0
        print("%s %s  [%s]" % (p["id"], p["title"], why))
        print(os.path.relpath(p["path"], ROOT).replace("\\", "/"))
    elif cmd == "list":
        want = sys.argv[2] if len(sys.argv) > 2 else None
        tasks = {t["id"]: t for t in game_tasks()}
        for p in load():
            if want and p["status"] != want:
                continue
            after = spec_waiting(p, tasks)
            print("%s %-10s %s%s" % (p["id"], p["status"], p["title"],
                                     ("  (spec after %04d)" % after) if after else ""))
    elif cmd == "status":
        if len(sys.argv) < 3:
            sys.exit("usage: assets.py status A012")
        packs = by_id(load())
        pid = sys.argv[2].upper()
        if pid not in packs:
            sys.exit("no pack %s" % pid)
        print(packs[pid]["status"])
    elif cmd == "set":
        if len(sys.argv) < 4:
            sys.exit("usage: assets.py set A012 <status> [note]")
        set_status(sys.argv[2].upper(), sys.argv[3],
                   sys.argv[4] if len(sys.argv) > 4 else "")
    elif cmd == "stats":
        packs = load()
        counts = {s: 0 for s in STATUSES}
        for p in packs:
            counts[p["status"]] = counts.get(p["status"], 0) + 1
        print("%d packs: %s" % (len(packs), ", ".join(
            "%d %s" % (counts[s], s) for s in STATUSES)))
    elif cmd == "index":
        write_index(load())
        print("INDEX.md rebuilt")
    elif cmd == "unblock":
        unblock()
    elif cmd == "check":
        return check()
    else:
        sys.exit(__doc__)
    return 0


if __name__ == "__main__":
    sys.exit(main())
