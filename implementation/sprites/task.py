"""Isolated art queue: next, stats, list, index, check, todo/doing/done/blocked ID [reason]."""
import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent
STATUS = re.compile(r"^- \*\*Status:\*\* (todo|doing|done|blocked)(?: - (.*))?$", re.M)
DEPS = re.compile(r"^- \*\*Depends on:\*\* (.+)$", re.M)
STATES = ("todo", "doing", "done", "blocked")


def load():
    tasks = []
    for path in sorted((ROOT / "prompts").glob("[0-9][0-9][0-9][0-9]-*.md")):
        body = path.read_text(encoding="utf-8")
        matches = list(STATUS.finditer(body))
        dep = DEPS.search(body)
        if len(matches) != 1 or dep is None:
            raise ValueError(f"{path.name}: expected one valid Status and Depends on line")
        tasks.append(dict(id=int(path.name[:4]), path=path, body=body,
                          title=re.sub(r"^# \d{4} - ", "", body.splitlines()[0]),
                          status=matches[0][1], note=matches[0][2] or "",
                          deps=[int(n) for n in re.findall(r"\b\d{4}\b", dep[1])]))
    validate(tasks)
    return tasks


def validate(tasks):
    by_id = {t["id"]: t for t in tasks}
    if not tasks or len(by_id) != len(tasks):
        raise ValueError("queue is empty or contains duplicate IDs")
    if sum(t["status"] == "doing" for t in tasks) > 1:
        raise ValueError("only one task can be doing")
    visiting, visited = set(), set()

    def visit(tid):
        if tid in visiting:
            raise ValueError(f"dependency cycle at {tid:04d}")
        if tid in visited:
            return
        visiting.add(tid)
        task = by_id[tid]
        for dep in task["deps"]:
            if dep not in by_id:
                raise ValueError(f"{tid:04d}: missing dependency {dep:04d}")
            visit(dep)
            if task["status"] in ("doing", "done") and by_id[dep]["status"] != "done":
                raise ValueError(f"{tid:04d}: active/completed task has unfinished dependency {dep:04d}")
        if task["status"] == "blocked" and not task["note"].strip():
            raise ValueError(f"{tid:04d}: blocked requires a reason")
        visiting.remove(tid)
        visited.add(tid)

    for tid in by_id:
        visit(tid)


def index_text(tasks):
    lines = ["# Sprite backlog", "", "Generated by `task.py index`; edit statuses through `task.py`.", "",
             "| Task | Status | Dependencies |", "|---|---|---|"]
    for task in tasks:
        check = "x" if task["status"] == "done" else " "
        deps = ", ".join(f"{d:04d}" for d in task["deps"]) or "none"
        lines.append(f"| [{check}] [{task['id']:04d} {task['title']}](prompts/{task['path'].name}) | {task['status']} | {deps} |")
    return "\n".join(lines) + "\n"


def write_index(tasks):
    (ROOT / "BACKLOG.md").write_text(index_text(tasks), encoding="utf-8", newline="\n")


def next_task(tasks):
    by_id = {t["id"]: t for t in tasks}
    return next((t for t in tasks if t["status"] == "doing"), None) or next(
        (t for t in tasks if t["status"] == "todo" and
         all(by_id[d]["status"] == "done" for d in t["deps"])), None)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("next", "stats", "list", "index", "check", *STATES))
    parser.add_argument("value", nargs="?")
    parser.add_argument("reason", nargs="?", default="")
    args = parser.parse_args()
    tasks = load()
    if args.command == "next":
        task = next_task(tasks)
        if task:
            print(f"{task['id']:04d} {task['title']} [{task['status']}]")
            print(f"implementation/sprites/prompts/{task['path'].name}")
        else:
            print("nothing actionable")
            for t in tasks:
                if t["status"] == "blocked":
                    print(f"{t['id']:04d} blocked: {t['note']}")
    elif args.command == "stats":
        print(f"{len(tasks)} tasks: " + ", ".join(f"{sum(t['status'] == s for t in tasks)} {s}" for s in STATES))
    elif args.command == "list":
        if args.value and args.value not in STATES:
            raise ValueError("list filter must be todo, doing, done or blocked")
        for t in tasks:
            if not args.value or t["status"] == args.value:
                print(f"{t['id']:04d} {t['status']:7} {t['title']}")
    elif args.command == "index":
        write_index(tasks)
        print("sprite BACKLOG.md rebuilt")
    elif args.command == "check":
        from plan import TASKS
        expected = {t[0]: t for t in TASKS}
        if {t["id"] for t in tasks} != set(expected):
            raise ValueError("prompt IDs disagree with plan.py; regenerate missing prompts")
        for t in tasks:
            if t["deps"] != expected[t["id"]][3]:
                raise ValueError(f"{t['id']:04d}: dependencies disagree with plan.py")
        index = ROOT / "BACKLOG.md"
        if not index.exists() or index.read_text(encoding="utf-8") != index_text(tasks):
            raise ValueError("BACKLOG.md is stale; run task.py index")
        print(f"PASS: {len(tasks)} prompts, valid dependencies/statuses and current index")
    else:
        if args.value is None:
            raise ValueError("status command requires a task ID")
        task = next((t for t in tasks if t["id"] == int(args.value)), None)
        if task is None:
            raise ValueError(f"unknown task {args.value}")
        task["status"], task["note"] = args.command, args.reason.strip()
        validate(tasks)  # Validate transition before touching any files.
        line = f"- **Status:** {args.command}" + (f" - {task['note']}" if task["note"] else "")
        task["path"].write_text(STATUS.sub(lambda _: line, task["body"], count=1),
                                encoding="utf-8", newline="\n")
        write_index(tasks)
        print(f"{task['id']:04d} -> {args.command}")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (ValueError, OSError) as error:
        print(f"FAIL: {error}", file=sys.stderr)
        sys.exit(1)
