"""The letters, as ASCII maps. `tools/gen_font.py` turns them into a font.

Same idea as `tools/sprite_maps.py` and for the same reason: the drawing is
the source and the file the game loads is build output, so nobody can paint
over a letter and have it stay painted.

## The cell

Every glyph is **eight rows of five**, written as one string with `/` between
the rows so that no glyph has an offset anybody can get wrong. The rows mean:

    row 0    the mark      acute, grave, circumflex, tilde, diaeresis, ring
    row 1    clear, and ascenders    b d f h k l t
    rows 2-6 cap height     A-Z, 0-9, most punctuation
    rows 3-6 x-height       a c e m n o r s u v w x z
    row 7    descender      g j p q y, and the cedilla's tail

The baseline is under row 6.

**The first version was seven rows and it was one short in two places.** With
the marks on rows 0 and 1 and the caps on 1 to 5, an accented letter had its
accent touching its letter; and a four-row cell left over for lowercase gave
an x-height of three, which rendered "the quick brown fox" as a row of
squares. Row 1 is empty on everything that can take a mark, which is what
buys the gap.

A glyph is trimmed to its ink when it is packed, so `I` is one pixel wide and
`M` is five - the font is proportional. **Digits are the exception and are
deliberately not trimmed**, which is what makes a counter tabular; see
`gen_font.py`.

## Coverage

The ninety-five printable ASCII characters are drawn here. The rest of
Latin-1 - every accented letter Portuguese needs at task 0097, and the rest
besides - is **composed** from these and the five marks at the bottom rather
than drawn again. `ACCENTED` is that table.
"""

